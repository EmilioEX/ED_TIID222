#Declarando un arreglo
numeros=[10,20,30,40,50]

#Imprime un elemento específico que se encuentre dentro del arreglo
print(numeros[2])

#Reasignación del valor de una posición
numeros[3]=35

#Imprimimos todo el arreglo
print(numeros)

#Agregar nuevo valor al final del arreglo
numeros.append(60)
print(numeros)

#Removemos un valor dentro del arreglo
numeros.remove(35)
print(numeros)

#Eliminamos un valor del arreglo utilizando la posición
numeros.pop(4)
print(numeros)

